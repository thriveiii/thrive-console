function getLang(){ return localStorage.getItem("thrive_lang") || "en"; }
function setLang(l){ localStorage.setItem("thrive_lang", l); applyLang(); }
function t(key){ const l=getLang(); return (I18N[l] && I18N[l][key]) || I18N.en[key] || key; }

function applyLang(){
  const l = getLang(), dict = I18N[l];
  document.documentElement.lang = l;
  document.documentElement.dir = dict._dir;
  document.querySelectorAll("[data-i18n]").forEach(el=>{ el.innerHTML = t(el.getAttribute("data-i18n")); });
  document.querySelectorAll("[data-i18n-ph]").forEach(el=>{ el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph")).replace(/&lt;/g,"<").replace(/&gt;/g,">")); });
  const lb = document.getElementById("langbtn");
  if(lb) lb.textContent = (l==="en") ? "العربية" : "English";
  /* Every data-i18n element was just rewritten from the dictionary, which wipes any symbol
     that lived inside it. Refilling here means one call covers the whole document and the
     language switch, and applyIcons is idempotent, so it costs nothing when nothing changed. */
  if(typeof applyIcons === "function") applyIcons();
  if(window.onLangApplied) window.onLangApplied();
}
/* Explanations for metrics: hover on a pointer device, tap the ⓘ on touch.
   One floating bubble, positioned near the trigger and kept inside the viewport. */
function initTips(){
  let bub=null;
  function hide(){ if(bub){ bub.remove(); bub=null; } }
  function show(btn){
    hide();
    const txt=btn.getAttribute("data-tip"); if(!txt) return;
    bub=document.createElement("div"); bub.className="tipbubble"; bub.textContent=txt;
    bub.setAttribute("dir", document.documentElement.dir||"ltr");
    document.body.appendChild(bub);
    const r=btn.getBoundingClientRect(), b=bub.getBoundingClientRect();
    let left=r.left+r.width/2-b.width/2;
    left=Math.max(10, Math.min(left, window.innerWidth-b.width-10));
    let top=r.top-b.height-10;
    if(top<8) top=r.bottom+10;                       // flip below when there is no room above
    bub.style.left=Math.round(left)+"px";
    bub.style.top=Math.round(top+window.scrollY)+"px";
    bub.classList.add("show");
  }
  document.addEventListener("click",e=>{
    const btn=e.target.closest && e.target.closest("[data-tip]");
    if(btn){ e.preventDefault(); e.stopPropagation();
      // On a device with BOTH pointer and touch, hover may have opened this already. Clicking
      // then pins it open, and only a second click on a pinned bubble closes it.
      if(bub && bub.__for===btn && bub.__pinned){ hide(); return; }
      if(!(bub && bub.__for===btn)) show(btn);
      if(bub){ bub.__for=btn; bub.__pinned=true; }
      return; }
    hide();
  });
  document.addEventListener("mouseover",e=>{
    if(!window.matchMedia || !window.matchMedia("(hover:hover)").matches) return;
    const btn=e.target.closest && e.target.closest("[data-tip]");
    if(btn && !(bub && bub.__for===btn)){ show(btn); if(bub){ bub.__for=btn; bub.__pinned=false; } }
  });
  document.addEventListener("mouseout",e=>{
    if(!window.matchMedia || !window.matchMedia("(hover:hover)").matches) return;
    const btn=e.target.closest && e.target.closest("[data-tip]");
    if(btn && bub && bub.__for===btn && !bub.__pinned) hide();   // pinned bubbles survive mouse-out
  });
  window.addEventListener("scroll", hide, {passive:true});
  window.addEventListener("resize", hide);
  document.addEventListener("keydown",e=>{ if(e.key==="Escape") hide(); });
}
function initLang(){
  const lb = document.getElementById("langbtn");
  if(lb) lb.addEventListener("click", ()=> setLang(getLang()==="en"?"ar":"en"));
  initTips();
  // perf: pause the spinning logo when the tab is hidden (saves CPU/battery)
  document.addEventListener("visibilitychange", ()=> document.documentElement.classList.toggle("tab-hidden", document.hidden));
  applyLang();
}

/* ============================================================================
   Thrive Console · board strings

   Merge these into the existing I18N object. Do not create a second dictionary.

   Arabic register: fluent simple MSA in the Gulf digital register.
   Guillemets «...» for quotes, Western numerals, no letter-spacing, no
   uppercase. See IDENTITY.md §7.

   ---------------------------------------------------------------------------
   WHY THIS FILE IS MORE THAN A STRING TABLE
   ---------------------------------------------------------------------------
   Arabic inflects the noun after a number, and it does so differently at 1, at
   2, at 3 to 10, at 11 to 99, and at 100 and above. A single template with {n}
   in it is wrong for most values. «3 ردّ» is not Arabic, and neither is
   «1 ردّوا».

   English needs two forms. Arabic needs five. So every string that carries a
   count is stored as a form object and `boardText()` chooses. This is not
   over-engineering. The board is a counting surface, nearly every sentence on
   it carries a number, and a product that miscounts in its second language is
   not bilingual, it is translated.

   Any future string that carries a number must be added as a form object.
   A flat "{n}" template holding a count is a defect.
   ============================================================================ */

